/*
Generalized all-tenure 13/1 retention build.

The recovered short SQL and the refresh runner were inconsistent. This template
reconstructs the missing projection/audit contract from the preserved runner.
See docs/snowflake_schema.md for the exact reconciliation. Python renders the
three markers and substitutes the configured generic database/schema names.
*/
CREATE OR REPLACE TABLE INSURANCE_ANALYTICS.RETENTION.POLICY_RETENTION_13_1
DATA_RETENTION_TIME_IN_DAYS = /*__DATA_RETENTION_TIME_IN_DAYS__*/
COPY GRANTS
COPY TAGS
AS
WITH RAW_HISTORY AS
(
    SELECT
        /*__RAW_HISTORY_PROJECTION__*/
    FROM INSURANCE_ANALYTICS.RETENTION.POLICY_EXPOSURE_HISTORY
),
RAW_TENURE_INPUTS AS
(
    SELECT
        R.*,
        UPPER(TRIM(TO_VARCHAR(R.TENURE_YEARS_GRP))) AS __RAW_TENURE_GROUP_VALUE,
        R.TENURE_YEARS_INT AS __RAW_TENURE_YEARS_INT
    FROM RAW_HISTORY AS R
),
CANONICAL_TENURE_INPUTS AS
(
    SELECT
        T.*,
        T.__RAW_TENURE_GROUP_VALUE AS __CANONICAL_TENURE_GROUP
    FROM RAW_TENURE_INPUTS AS T
),
SOURCE_HISTORY AS
(
    SELECT
        S.* EXCLUDE (TENURE_YEARS_GRP),
        S.__CANONICAL_TENURE_GROUP AS TENURE_YEARS_GRP
    FROM CANONICAL_TENURE_INPUTS AS S
),
/* Rate and deductible construction uses the earliest exposure row per term.
   The Python refresh contract requires this independently of the latest
   active row used for the remaining Month-1 snapshot attributes. */
TERM_SOURCE_ROWS AS
(
    SELECT
        R.*,
        ROW_NUMBER() OVER
        (
            PARTITION BY R.POLICY_CONTRACT_ID, R.POLICY_TERM_START_DATE::DATE
            ORDER BY
                R.EXPOSURE_START_DATE::DATE ASC NULLS LAST,
                TO_VARCHAR(R.EXPOSURE_ROW_ID) ASC NULLS LAST
        ) AS __TERM_SOURCE_ROW_NUMBER
    FROM SOURCE_HISTORY AS R
    WHERE R.POLICY_TERM_START_DATE IS NOT NULL
),
TERM_BASE_FEATURES AS
(
    SELECT
        M.POLICY_CONTRACT_ID,
        M.POLICY_TERM_START_DATE::DATE AS TERM_START_DATE,
        M.COV_A_DWELLING_CVG_AMT,
        SPLIT_PART(M.DED_ALLPERIL_OFST_NOTREND, '_', 1) AS DED_RAW,
        CASE
            WHEN M.EARNED_EXPOSURE_VALUE <= 0 THEN 0
            ELSE M.TOT_ERND_PREM_AMT / M.EARNED_EXPOSURE_VALUE
        END AS WRITTEN_PREM
    FROM TERM_SOURCE_ROWS AS M
    WHERE M.__TERM_SOURCE_ROW_NUMBER = 1
),
TERM_PARSED_FEATURES AS
(
    SELECT
        B.*,
        CASE
            WHEN CONTAINS(B.DED_RAW, '%')
                THEN B.COV_A_DWELLING_CVG_AMT
                     * TO_NUMBER(REPLACE(B.DED_RAW, '%', '')) / 100
            ELSE TO_NUMBER(B.DED_RAW)
        END AS DED_PROCESS
    FROM TERM_BASE_FEATURES AS B
),
TERM_BANDS_AND_PREVIOUS_PREMIUM AS
(
    SELECT
        P.*,
        CASE
            WHEN P.DED_PROCESS <= 500 THEN '000500'
            WHEN P.DED_PROCESS <= 1000 THEN '001000'
            WHEN P.DED_PROCESS <= 1500 THEN '001500'
            WHEN P.DED_PROCESS <= 2500 THEN '002500'
            WHEN P.DED_PROCESS <= 5000 THEN '005000'
            WHEN P.DED_PROCESS <= 10000 THEN '010000'
            WHEN P.DED_PROCESS > 10000 THEN '10000+'
            ELSE 'NA'
        END AS DED_FINAL,
        LAG(P.WRITTEN_PREM) OVER
        (
            PARTITION BY P.POLICY_CONTRACT_ID ORDER BY P.TERM_START_DATE
        ) AS PREV_WRITTEN_PREM
    FROM TERM_PARSED_FEATURES AS P
),
TERM_FEATURES AS
(
    SELECT
        G.*,
        CASE
            WHEN G.PREV_WRITTEN_PREM IS NULL THEN NULL
            WHEN G.WRITTEN_PREM = 0 THEN NULL
            ELSE (G.WRITTEN_PREM - G.PREV_WRITTEN_PREM)
                 / G.WRITTEN_PREM * 100
        END AS RATE_CHANGE,
        CASE
            WHEN G.PREV_WRITTEN_PREM IS NULL THEN -100
            WHEN G.WRITTEN_PREM = 0 THEN NULL
            ELSE (G.WRITTEN_PREM - G.PREV_WRITTEN_PREM)
                 / G.WRITTEN_PREM * 100
        END AS RATE_CHANGE2
    FROM TERM_BANDS_AND_PREVIOUS_PREMIUM AS G
),
COVERAGE_INTERVALS AS
(
    SELECT
        POLICY_CONTRACT_ID,
        POLICY_INCEPTION_DATE::DATE AS POLICY_INCEPTION_DATE,
        EXPOSURE_START_DATE::DATE AS COVERAGE_START_DATE,
        COALESCE(EXPOSURE_END_DATE::DATE, DATE '2024-12-31') AS COVERAGE_END_DATE,
        POLICY_TERM_START_DATE::DATE AS TERM_START_DATE,
        POLICY_TERM_END_DATE::DATE AS TERM_END_DATE,
        TENURE_YEARS_GRP
    FROM SOURCE_HISTORY
),
ANCHOR_TERMS AS
(
    SELECT
        POLICY_CONTRACT_ID,
        POLICY_TERM_START_DATE::DATE AS ANCHOR_TERM_START_DATE,
        MAX(POLICY_TERM_END_DATE)::DATE AS ANCHOR_TERM_END_DATE,
        MIN(TENURE_YEARS_GRP) AS ANCHOR_TENURE_YEARS_GRP,
        MIN(TENURE_YEARS_INT)::FLOAT AS ANCHOR_TENURE_YEARS_INT,
        COUNT(DISTINCT TENURE_YEARS_GRP)
            + IFF(COALESCE(COUNT_IF(TENURE_YEARS_GRP IS NULL), 0) > 0, 1, 0)
            AS ANCHOR_TENURE_VALUE_COUNT,
        COUNT(DISTINCT POLICY_TERM_END_DATE::DATE)
            + IFF(COALESCE(COUNT_IF(POLICY_TERM_END_DATE IS NULL), 0) > 0, 1, 0)
            AS ANCHOR_TERM_END_VALUE_COUNT,
        MIN(EXPOSURE_START_DATE)::DATE AS ANCHOR_MIN_EXPSR_EFF_DT
    FROM SOURCE_HISTORY
    GROUP BY POLICY_CONTRACT_ID, POLICY_TERM_START_DATE::DATE
),
VALID_MATURE_ANCHOR_TERMS AS
(
    SELECT
        T.*,
        DATEADD(DAY, 30, T.ANCHOR_TERM_START_DATE) AS MONTH_1_EVALUATION_DATE,
        DATEADD(DAY, 30, T.ANCHOR_TERM_END_DATE) AS MONTH_13_EVALUATION_DATE
    FROM ANCHOR_TERMS AS T
    WHERE T.ANCHOR_TENURE_YEARS_GRP IN ('0', '1', '2', '3', '4+')
      AND T.ANCHOR_TENURE_VALUE_COUNT = 1
      AND T.ANCHOR_TERM_END_VALUE_COUNT = 1
      AND DATEDIFF(DAY, T.ANCHOR_TERM_START_DATE, T.ANCHOR_TERM_END_DATE)
              BETWEEN 360 AND 370
      AND DATEADD(DAY, 30, T.ANCHOR_TERM_END_DATE) <= DATE '2024-12-31'
      AND T.ANCHOR_TERM_START_DATE < DATE '2024-01-01'
),
MONTH_1_SNAPSHOT AS
(
    SELECT
        S.*,
        T.* EXCLUDE (POLICY_CONTRACT_ID)
    FROM SOURCE_HISTORY AS S
    INNER JOIN VALID_MATURE_ANCHOR_TERMS AS T
        ON T.POLICY_CONTRACT_ID = S.POLICY_CONTRACT_ID
       AND T.ANCHOR_TERM_START_DATE = S.POLICY_TERM_START_DATE::DATE
    WHERE S.EXPOSURE_START_DATE::DATE <= T.MONTH_1_EVALUATION_DATE
      AND COALESCE(S.EXPOSURE_END_DATE::DATE, DATE '2024-12-31')
              >= T.MONTH_1_EVALUATION_DATE
    QUALIFY ROW_NUMBER() OVER
    (
        PARTITION BY S.POLICY_CONTRACT_ID, T.ANCHOR_TERM_START_DATE
        ORDER BY
            S.EXPOSURE_START_DATE::DATE DESC NULLS LAST,
            S.EXPOSURE_END_DATE::DATE DESC NULLS LAST,
            TO_VARCHAR(S.EXPOSURE_ROW_ID) ASC NULLS LAST
    ) = 1
),
MONTH_13_STATUS AS
(
    SELECT
        A.POLICY_CONTRACT_ID,
        A.ANCHOR_TERM_START_DATE,
        IFF(COUNT(H.POLICY_CONTRACT_ID) > 0, 1, 0) AS ACTIVE_AT_MONTH_13_IND
    FROM MONTH_1_SNAPSHOT AS A
    LEFT JOIN COVERAGE_INTERVALS AS H
        ON H.POLICY_CONTRACT_ID = A.POLICY_CONTRACT_ID
       AND H.COVERAGE_START_DATE <= A.MONTH_13_EVALUATION_DATE
       AND H.COVERAGE_END_DATE >= A.MONTH_13_EVALUATION_DATE
    GROUP BY A.POLICY_CONTRACT_ID, A.ANCHOR_TERM_START_DATE
),
POLICY_COVERAGE_BOUNDS AS
(
    SELECT
        POLICY_CONTRACT_ID,
        MAX(COVERAGE_END_DATE) AS POLICY_MAX_EXPSR_END_EFF_DT
    FROM COVERAGE_INTERVALS
    GROUP BY POLICY_CONTRACT_ID
),
TENURE_ZERO_COMPATIBILITY AS
(
    SELECT
        POLICY_CONTRACT_ID,
        MAX(COVERAGE_END_DATE) AS NB_MAX_EXPSR_END_EFF_DT,
        MIN(COVERAGE_START_DATE) AS NB_MIN_EXPSR_EFF_DT,
        MAX(TERM_END_DATE) AS NB_POLICY_TERM_END_DATE,
        MIN(TERM_START_DATE) AS NB_POLICY_TERM_START_DATE
    FROM COVERAGE_INTERVALS
    WHERE TENURE_YEARS_GRP = '0'
    GROUP BY POLICY_CONTRACT_ID
),
ELIGIBLE_ANCHOR_TERMS AS
(
    SELECT
        A.*,
        C.POLICY_MAX_EXPSR_END_EFF_DT,
        F.DED_RAW,
        F.DED_PROCESS,
        F.DED_FINAL,
        F.WRITTEN_PREM,
        F.PREV_WRITTEN_PREM,
        F.RATE_CHANGE,
        F.RATE_CHANGE2,
        N.NB_MAX_EXPSR_END_EFF_DT,
        N.NB_MIN_EXPSR_EFF_DT,
        N.NB_POLICY_TERM_END_DATE,
        N.NB_POLICY_TERM_START_DATE,
        1 AS ACTIVE_AT_MONTH_1_IND,
        M.ACTIVE_AT_MONTH_13_IND,
        M.ACTIVE_AT_MONTH_13_IND AS RETENTION_13_1_IND
    FROM MONTH_1_SNAPSHOT AS A
    INNER JOIN MONTH_13_STATUS AS M
        ON M.POLICY_CONTRACT_ID = A.POLICY_CONTRACT_ID
       AND M.ANCHOR_TERM_START_DATE = A.ANCHOR_TERM_START_DATE
    LEFT JOIN TERM_FEATURES AS F
        ON F.POLICY_CONTRACT_ID = A.POLICY_CONTRACT_ID
       AND F.TERM_START_DATE = A.ANCHOR_TERM_START_DATE
    LEFT JOIN POLICY_COVERAGE_BOUNDS AS C
        ON C.POLICY_CONTRACT_ID = A.POLICY_CONTRACT_ID
    LEFT JOIN TENURE_ZERO_COMPATIBILITY AS N
        ON N.POLICY_CONTRACT_ID = A.POLICY_CONTRACT_ID
)
SELECT
    /*__FINAL_OUTPUT_PROJECTION__*/
FROM ELIGIBLE_ANCHOR_TERMS;
